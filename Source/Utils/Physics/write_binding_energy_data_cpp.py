"""
This python script reads the binding energies of the electrons of the neutral atoms in
binding_energy_data.txt and writes them into the C++ file BindingEnergiesTable.H.
The table has the same layout as the table of ionization energies in IonizationEnergiesTable.H
(generated by write_atomic_data_cpp.py): the binding energies of the element with ID i start
at index ion_energy_offsets[i].
"""

import os

filename = os.path.join(".", "binding_energy_data.txt")
elements = []
with open(filename) as f:
    for line in f:
        if line.startswith("#") or not line.strip():
            continue
        fields = line.split()
        atomic_number = int(fields[0])
        energies = fields[2:]
        assert len(energies) == atomic_number
        # The electrons are listed from the most bound to the least bound
        assert all(
            float(energies[i]) >= float(energies[i + 1])
            for i in range(atomic_number - 1)
        )
        elements.append((atomic_number, fields[1], energies))
assert [element[0] for element in elements] == list(range(1, len(elements) + 1))

# Head of CPP file
cpp_string = "// This script was automatically generated!\n"
cpp_string += (
    "// Edit dev/Source/Utils/Physics/write_binding_energy_data_cpp.py instead!\n\n"
)
cpp_string += "#ifndef WARPX_UTILS_PHYSICS_BINDING_ENERGIES_TABLE_H_\n"
cpp_string += "#define WARPX_UTILS_PHYSICS_BINDING_ENERGIES_TABLE_H_\n\n"
cpp_string += "#include <AMReX_REAL.H>\n\n"
cpp_string += "namespace utils::physics\n"
cpp_string += "{\n"
cpp_string += (
    "    // Binding energies [eV] of the electrons of the neutral atoms, from the most bound\n"
    "    // to the least bound electron (see binding_energy_data.txt for the source of the data).\n"
    "    // The binding energies of the element with ID i (see ion_map_ids in\n"
    "    // IonizationEnergiesTable.H) start at index ion_energy_offsets[i].\n"
)
n_values = sum(element[0] for element in elements)
cpp_string += (
    "    constexpr int binding_energies_tab_length = " + str(n_values) + ";\n\n"
)
cpp_string += "    constexpr amrex::Real table_neutral_binding_energies[binding_energies_tab_length]{"
for atomic_number, name, energies in elements:
    cpp_string += "\n        // " + name + "\n        "
    for count, energy in enumerate(energies):
        if count % 3 == 0 and count > 0:
            cpp_string = cpp_string[:-1] + "\n        "
        cpp_string += "amrex::Real(" + energy + "), "
    cpp_string = cpp_string[:-1]
cpp_string = cpp_string[:-1]
cpp_string += "\n    };\n\n"

cpp_string += "}\n\n"

# Write the string to file
cpp_string += "#endif // #ifndef WARPX_UTILS_PHYSICS_BINDING_ENERGIES_TABLE_H_\n"
with open("BindingEnergiesTable.H", "w") as f:
    f.write(cpp_string)
